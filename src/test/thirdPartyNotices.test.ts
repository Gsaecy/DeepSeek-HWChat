import assert from 'node:assert/strict';
import { existsSync, readFileSync } from 'node:fs';
import test from 'node:test';

/**
 * 开源许可证合规。
 *
 * 背景（用户要求）：「爬虫功能，参考 GitHub 上高 star 的爬虫开源项目，
 * 如果直接用了，记得符合开源协议。」
 *
 * 我们把第三方库 **bundle 进 `out/extension.js` 再发布 VSIX**，这属于再分发：
 * MIT / BSD-2-Clause / ISC 都要求随分发附带**版权声明与许可全文**。
 * 所以仓库根必须有一份 `THIRD-PARTY-NOTICES.md`，内容由脚本按**实际打包进来的**
 * 依赖生成，并且这份文件要被打进 VSIX。
 *
 * 这里守的就是这三件事：文件存在且被生成、随包发布、且不允许出现「声明了依赖却
 * 没在 notices 里」的漂移。
 */

const NOTICES = 'THIRD-PARTY-NOTICES.md';
const IGNORE = '.vscodeignore';
const PKG = JSON.parse(readFileSync('package.json', 'utf8')) as {
  dependencies?: Record<string, string>;
  scripts?: Record<string, string>;
};

test('存在第三方许可证清单，且按实际打包的依赖生成', () => {
  assert.ok(existsSync(NOTICES), '缺少 THIRD-PARTY-NOTICES.md');
  const text = readFileSync(NOTICES, 'utf8');
  assert.match(text, /generated by `scripts\/third-party-notices\.mjs`/, '要说明来源，避免手写成过期清单');
  assert.match(text, /actually reachable from the extension entry point/, '要说明「按实际打进包」而不是按 dependencies 写');
  // 至少要有包表 + 每个包的许可证全文段落
  assert.match(text, /\| Package \| Version \| License \|/);
  assert.ok((text.match(/^## /gm) ?? []).length >= 1, '每一条都要有许可证全文');
});

test('正文抽取库 defuddle 已署名（MIT 要求附版权与许可全文）', () => {
  const text = readFileSync(NOTICES, 'utf8');
  assert.match(text, /`defuddle` \| \d+\.\d+\.\d+ \| MIT/, 'defuddle 必须列在清单里');
  // MIT 全文的关键句：少了它等于没有满足署名条件
  assert.match(text, /Permission is hereby granted, free of charge/, '缺少 MIT 许可正文');
  assert.match(text, /THE SOFTWARE IS PROVIDED "AS IS"/, '缺少 MIT 免责声明');
});

test('清单覆盖 package.json 里的全部运行时依赖（防漂移）', () => {
  const text = readFileSync(NOTICES, 'utf8');
  for (const name of Object.keys(PKG.dependencies ?? {})) {
    assert.ok(text.includes(`\`${name}\``), `${name} 是运行时依赖，但 notices 里没有它`);
  }
});

test('notices 会被打进 VSIX，且打包前自动重新生成', () => {
  const ignore = readFileSync(IGNORE, 'utf8');
  assert.equal(
    ignore.split('\n').some((line) => line.trim() === NOTICES || line.trim() === '*.md' || line.trim() === '**/*.md'),
    false,
    '.vscodeignore 不能排除 THIRD-PARTY-NOTICES.md',
  );
  const pack = PKG.scripts?.package ?? '';
  assert.match(pack, /scripts\/third-party-notices\.mjs/, 'package 脚本必须先跑生成器');
  assert.ok(PKG.scripts?.notices, '要有一个可单独执行的 notices 脚本');
});

test('生成器会在缺许可证文件时失败（不允许静默漏署名）', () => {
  const script = readFileSync('scripts/third-party-notices.mjs', 'utf8');
  assert.match(script, /metafile: true/, '必须按真实构建的 metafile 统计');
  assert.match(script, /process\.exit\(1\)/, '缺许可证时要让打包失败');
  assert.match(script, /node_modules\\\//, '要从输入路径反推包名（而不是读 dependencies）');
});
