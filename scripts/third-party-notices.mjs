/**
 * 生成 THIRD-PARTY-NOTICES.md —— 按**实际打进包**的第三方依赖收集许可证全文。
 *
 * 为什么要有这个脚本，而不是手写一份清单：
 *  1. 手写清单一定会漂：升级依赖、换掉正文抽取库之后，谁也不会记得回来改它；
 *  2. MIT / BSD-2-Clause / ISC 都要求**随分发附带版权声明与许可全文**，
 *     我们把这些库 bundle 进 `out/extension.js` 再发布 VSIX，属于再分发；
 *  3. 「按实际打进包」才是准确的：`package.json` 里的 dependencies 与真正被
 *     import 进来的模块并不是一回事（有些包只在开发期用）。
 *
 * 做法：用 esbuild 以真实入口（src/extension.ts）构建一次，只取 metafile 里的输入
 * 路径 → 反推 node_modules 里的包名 → 读各自的 LICENSE 全文。任何被打进包的包
 * 如果没有许可证文件，脚本直接失败（宁可打包中断，也不要静默漏掉署名）。
 *
 * 运行：node scripts/third-party-notices.mjs（已接进 `npm run package`）
 */
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { build } from 'esbuild';

const ENTRY = 'src/extension.ts';
const OUTPUT = 'THIRD-PARTY-NOTICES.md';
const LICENSE_FILES = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'license', 'LICENCE', 'COPYING'];

/** 从 metafile 的输入路径里收集 node_modules 包名（含 scope）。 */
function collectPackages(metafile) {
  const found = new Set();
  for (const path of Object.keys(metafile.inputs)) {
    const match = path.match(/node_modules\/((?:@[^/]+\/)?[^/]+)\//);
    if (match) found.add(match[1]);
  }
  return [...found].sort();
}

function readPackage(file) {
  try {
    return JSON.parse(readFileSync(file, 'utf8'));
  } catch {
    return undefined;
  }
}

function licenseText(dir) {
  for (const name of LICENSE_FILES) {
    const file = join(dir, name);
    if (existsSync(file)) {
      const text = readFileSync(file, 'utf8').trim();
      if (text) return { file: name, text };
    }
    // `license` 有时是目录（含多个文件），这里只取常见文件名，避免把无关内容拼进来。
    if (existsSync(file) && readdirSync(file).length) {
      for (const inner of readdirSync(file)) {
        if (LICENSE_FILES.includes(inner)) {
          const nested = readFileSync(join(file, inner), 'utf8').trim();
          if (nested) return { file: `${name}/${inner}`, text: nested };
        }
      }
    }
  }
  return undefined;
}

const result = await build({
  entryPoints: [ENTRY],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'node',
  external: ['vscode'],
  minify: true,
  target: 'node20',
  logLevel: 'silent',
  metafile: true,
});

const packages = collectPackages(result.metafile);
const entries = [];
const missing = [];

for (const name of packages) {
  const dir = join('node_modules', name);
  const meta = readPackage(join(dir, 'package.json'));
  const license = licenseText(dir);
  if (!meta || !license) {
    missing.push(name);
    continue;
  }
  entries.push({
    name,
    version: String(meta.version ?? ''),
    declared: String(meta.license ?? meta.licenses ?? ''),
    homepage: String(meta.homepage ?? meta.repository?.url ?? ''),
    text: license.text,
  });
}

if (missing.length) {
  console.error(`✗ 以下包被打进 bundle 但没有许可证文件，无法合规署名：${missing.join(', ')}`);
  process.exit(1);
}

const lines = [
  '# Third-Party Notices',
  '',
  'HWChat bundles the following third-party open-source packages into `out/extension.js`.',
  'Each package remains under its own license; the full license text is reproduced below,',
  'which is what the MIT, BSD-2-Clause and ISC licenses require when redistributing.',
  '',
  'This file is generated by `scripts/third-party-notices.mjs` from the packages that are',
  '**actually reachable from the extension entry point**, so it cannot drift from the build.',
  '',
  `Packages: ${entries.length}`,
  '',
  '| Package | Version | License |',
  '| --- | --- | --- |',
  ...entries.map((entry) => `| \`${entry.name}\` | ${entry.version} | ${entry.declared} |`),
  '',
];

for (const entry of entries) {
  lines.push(`## ${entry.name} ${entry.version}`, '');
  lines.push(`- License: ${entry.declared}`);
  if (entry.homepage) lines.push(`- Source: ${entry.homepage}`);
  lines.push('', '```text', entry.text, '```', '');
}

writeFileSync(OUTPUT, `${lines.join('\n').trimEnd()}\n`, 'utf8');
console.log(`✓ ${OUTPUT}：${entries.length} 个第三方包，许可证全文已收录`);
